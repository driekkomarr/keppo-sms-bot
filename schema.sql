-- ========================================================
-- Supabase Schema for Telegram OTP Bot (OMAR OTP Bot)
-- ========================================================

-- 1. Create 'users' table
CREATE TABLE IF NOT EXISTS public.users (
    telegram_id BIGINT PRIMARY KEY,
    username TEXT DEFAULT 'Anonymous',
    balance NUMERIC(10, 2) DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 2. Create 'activations' table (SMS leases and OTP logs)
CREATE TABLE IF NOT EXISTS public.activations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activation_id TEXT NOT NULL UNIQUE,
    telegram_id BIGINT NOT NULL,
    service TEXT NOT NULL,
    amount NUMERIC(10, 2) DEFAULT 0.00,
    phone_number TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 3. Create 'topup_logs' table (Tracks revenue & balance credits)
CREATE TABLE IF NOT EXISTS public.topup_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 4. Grant table & sequence privileges to Supabase roles
GRANT ALL ON TABLE public.users TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.activations TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.topup_logs TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL ROUTINES IN SCHEMA public TO anon, authenticated, service_role;

-- 5. Enable Row Level Security (RLS) - Recommended
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.activations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.topup_logs ENABLE ROW LEVEL SECURITY;

-- Allow full access to all roles
DROP POLICY IF EXISTS "Allow full access to users" ON public.users;
DROP POLICY IF EXISTS "Allow full access to activations" ON public.activations;
DROP POLICY IF EXISTS "Allow full access to topup_logs" ON public.topup_logs;
CREATE POLICY "Allow full access to users" ON public.users FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow full access to activations" ON public.activations FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow full access to topup_logs" ON public.topup_logs FOR ALL USING (true) WITH CHECK (true);

-- 5. RPC Function: deduct_balance
-- Atomically deducts cost from user's balance if sufficient funds exist.
CREATE OR REPLACE FUNCTION deduct_balance(user_id BIGINT, cost NUMERIC)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    current_bal NUMERIC;
BEGIN
    SELECT balance INTO current_bal 
    FROM public.users 
    WHERE telegram_id = user_id 
    FOR UPDATE;

    IF current_bal IS NULL OR current_bal < cost THEN
        RETURN FALSE;
    END IF;

    UPDATE public.users 
    SET balance = balance - cost 
    WHERE telegram_id = user_id;

    RETURN TRUE;
END;
$$;

-- 6. RPC Function: refund_balance
-- Atomically adds funds to user's balance and returns the new balance.
CREATE OR REPLACE FUNCTION refund_balance(user_id BIGINT, refund_amount NUMERIC)
RETURNS NUMERIC
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    new_bal NUMERIC;
BEGIN
    INSERT INTO public.users (telegram_id, balance)
    VALUES (user_id, refund_amount)
    ON CONFLICT (telegram_id)
    DO UPDATE SET balance = public.users.balance + refund_amount
    RETURNING balance INTO new_bal;

    RETURN new_bal;
END;
$$;

